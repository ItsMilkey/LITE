-- Crea el esquema completo de SaveUp Lite de forma idempotente.
-- CREATE TABLE IF NOT EXISTS disponible desde Oracle 23c.
-- Todos los tipos usan sintaxis nativa Oracle.
-- ============================================================

-- 3.1 USUARIO
CREATE TABLE IF NOT EXISTS USUARIO (
    ID_USUARIO      VARCHAR2(255)  NOT NULL,
    NOMBRE          VARCHAR2(255)  NOT NULL,
    APELLIDO        VARCHAR2(255)  NOT NULL,
    EMAIL           VARCHAR2(255)  NOT NULL,
    CONTRASENA_HASH VARCHAR2(100)  NOT NULL,
    FECHA_REGISTRO  TIMESTAMP      NOT NULL,
    CONSTRAINT PK_USUARIO        PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_EMAIL  UNIQUE      (EMAIL)
);

-- 3.2 CATEGORIA
CREATE TABLE IF NOT EXISTS CATEGORIA (
    ID_CATEGORIA     NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE           VARCHAR2(255)  NOT NULL,
    ICON_ID          VARCHAR2(255),
    COLOR_HEX        VARCHAR2(20),
    TIPO_PRESUPUESTO VARCHAR2(20),
    CONSTRAINT PK_CATEGORIA         PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_CATEGORIA_NOMBRE  UNIQUE      (NOMBRE),
    CONSTRAINT CHK_CATEGORIA_TIPO   CHECK (TIPO_PRESUPUESTO IN ('NECESIDAD','DESEO','AHORRO','OTROS'))
);

-- 3.4 META_AHORRO  (antes de MOVIMIENTO porque MOVIMIENTO referencia META_AHORRO)
CREATE TABLE IF NOT EXISTS META_AHORRO (
    ID_META         NUMBER          GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE          VARCHAR2(100)   NOT NULL,
    MONTO_OBJETIVO  NUMBER(19, 2),
    MONTO_ACTUAL    NUMBER(19, 2)   DEFAULT 0.00,
    FECHA_LIMITE    DATE,
    USUARIO_ID      VARCHAR2(255)   NOT NULL,
    CONSTRAINT PK_META_AHORRO  PRIMARY KEY (ID_META),
    CONSTRAINT FK_META_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID_USUARIO)
);

-- 3.5 DEUDA  (antes de MOVIMIENTO porque MOVIMIENTO referencia DEUDA)
CREATE TABLE IF NOT EXISTS DEUDA (
    ID_DEUDA        NUMBER          GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE          VARCHAR2(100)   NOT NULL,
    DESCRIPCION     VARCHAR2(255),
    MONTO_TOTAL     NUMBER(19, 2)   NOT NULL,
    CANTIDAD_CUOTAS NUMBER(10, 0)   NOT NULL,
    ESTADO          VARCHAR2(20)    NOT NULL,
    FECHA_CREACION  TIMESTAMP       NOT NULL,
    USUARIO_ID      VARCHAR2(255)   NOT NULL,
    CONSTRAINT PK_DEUDA        PRIMARY KEY (ID_DEUDA),
    CONSTRAINT FK_DEUDA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT CHK_DEUDA_ESTADO CHECK (ESTADO IN ('PENDIENTE','PAGADA','CANCELADA'))
);

-- 3.3 MOVIMIENTO
CREATE TABLE IF NOT EXISTS MOVIMIENTO (
    ID_MOVIMIENTO   NUMBER          GENERATED BY DEFAULT AS IDENTITY,
    MONTO           NUMBER(19, 2)   NOT NULL,
    DESCRIPCION     VARCHAR2(100)   NOT NULL,
    FECHA           TIMESTAMP       NOT NULL,
    TIPO_MOVIMIENTO VARCHAR2(30)    NOT NULL,
    USUARIO_ID      VARCHAR2(255)   NOT NULL,
    DEUDA_ID        NUMBER,
    CATEGORIA_ID    NUMBER,
    META_ID         NUMBER,
    CONSTRAINT PK_MOVIMIENTO      PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_MOV_USUARIO     FOREIGN KEY (USUARIO_ID)    REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_MOV_DEUDA       FOREIGN KEY (DEUDA_ID)      REFERENCES DEUDA(ID_DEUDA),
    CONSTRAINT FK_MOV_CATEGORIA   FOREIGN KEY (CATEGORIA_ID)  REFERENCES CATEGORIA(ID_CATEGORIA),
    CONSTRAINT FK_MOV_META        FOREIGN KEY (META_ID)       REFERENCES META_AHORRO(ID_META),
    CONSTRAINT CHK_MOV_TIPO CHECK (TIPO_MOVIMIENTO IN ('INGRESO_GENERAL','GASTO_GENERAL','PAGO_DEUDA','ABONO_META','RETIRO_META'))
);

-- 3.6 CONFIGURACION_PRESUPUESTO
-- NUMBER(1): 1 = true, 0 = false  (Hibernate OracleDialect mapea Boolean a number(1,0))
CREATE TABLE IF NOT EXISTS CONFIGURACION_PRESUPUESTO (
    ID_CONFIGURACION            NUMBER        GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID                  VARCHAR2(255) NOT NULL,
    PORCENTAJE_NECESIDADES      NUMBER(5, 2)  NOT NULL,
    PORCENTAJE_DESEOS           NUMBER(5, 2)  NOT NULL,
    PORCENTAJE_AHORRO           NUMBER(5, 2)  NOT NULL,
    ACTIVO                      NUMBER(1)     DEFAULT 1 NOT NULL,
    AUTOMATIZAR_AHORRO_EN_METAS NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONF_PRESUPUESTO  PRIMARY KEY (ID_CONFIGURACION),
    CONSTRAINT UQ_CONF_USUARIO      UNIQUE      (USUARIO_ID),
    CONSTRAINT FK_CONF_USUARIO      FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID_USUARIO)
);

-- 3.7 ASIGNACION_META_PRESUPUESTO
CREATE TABLE IF NOT EXISTS ASIGNACION_META_PRESUPUESTO (
    ID_ASIGNACION         NUMBER       GENERATED BY DEFAULT AS IDENTITY,
    CONFIGURACION_ID      NUMBER       NOT NULL,
    META_ID               NUMBER       NOT NULL,
    PORCENTAJE_ASIGNACION NUMBER(5, 2) NOT NULL,
    CONSTRAINT PK_ASIGNACION    PRIMARY KEY (ID_ASIGNACION),
    CONSTRAINT FK_ASIG_CONFIG   FOREIGN KEY (CONFIGURACION_ID) REFERENCES CONFIGURACION_PRESUPUESTO(ID_CONFIGURACION),
    CONSTRAINT FK_ASIG_META     FOREIGN KEY (META_ID)          REFERENCES META_AHORRO(ID_META)
);
