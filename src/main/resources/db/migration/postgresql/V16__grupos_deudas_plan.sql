-- ============================================================
-- V16__grupos_deudas_plan.sql  |  PostgreSQL
-- T10d (sesión 2): grupos del plan y deudas vinculadas.
-- ============================================================
-- Reglas de esquema:
--   * Un grupo pertenece a un usuario y su nombre es único por usuario
--     (normalizado en minúsculas y sin tildes).
--   * `partida_plan.grupo_id` usa ON DELETE SET NULL: borrar el grupo deja las
--     partidas sin grupo, nunca las borra.
--   * `partida_plan.deuda_id` usa ON DELETE SET NULL y el índice único parcial
--     garantiza una sola partida por (plan, deuda) en PostgreSQL.
--   * RLS activo en la tabla nueva (regla de V8/V12).
--   * Sin DDL contra migraciones anteriores más allá de las columnas nuevas.
-- ============================================================

CREATE TABLE IF NOT EXISTS grupo_plan (
    id_grupo_plan      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id         VARCHAR(255) NOT NULL,
    nombre             VARCHAR(60)  NOT NULL,
    nombre_normalizado VARCHAR(60)  NOT NULL,
    orden              INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_grupo_plan        PRIMARY KEY (id_grupo_plan),
    CONSTRAINT fk_grupo_usuario     FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT uq_grupo_usuario_nombre UNIQUE (usuario_id, nombre_normalizado)
);

CREATE INDEX IF NOT EXISTS idx_grupo_usuario ON grupo_plan (usuario_id);

ALTER TABLE partida_plan ADD COLUMN IF NOT EXISTS grupo_id BIGINT;
ALTER TABLE partida_plan ADD COLUMN IF NOT EXISTS deuda_id BIGINT;

ALTER TABLE partida_plan DROP CONSTRAINT IF EXISTS fk_partida_grupo;
ALTER TABLE partida_plan
    ADD CONSTRAINT fk_partida_grupo FOREIGN KEY (grupo_id)
    REFERENCES grupo_plan(id_grupo_plan) ON DELETE SET NULL;

ALTER TABLE partida_plan DROP CONSTRAINT IF EXISTS fk_partida_deuda;
ALTER TABLE partida_plan
    ADD CONSTRAINT fk_partida_deuda FOREIGN KEY (deuda_id)
    REFERENCES deuda(id_deuda) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_partida_grupo ON partida_plan (grupo_id);
CREATE INDEX IF NOT EXISTS idx_partida_deuda ON partida_plan (deuda_id);

-- Una sola partida por deuda dentro del mismo plan. El índice parcial omite
-- las partidas sin deuda (deuda_id NULL).
CREATE UNIQUE INDEX IF NOT EXISTS uq_partida_plan_deuda
    ON partida_plan (plan_id, deuda_id)
    WHERE deuda_id IS NOT NULL;

ALTER TABLE grupo_plan ENABLE ROW LEVEL SECURITY;
