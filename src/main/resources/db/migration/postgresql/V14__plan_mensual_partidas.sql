-- ============================================================
-- V14__plan_mensual_partidas.sql  |  PostgreSQL
-- T10c: plan del mes, partidas y vínculo opcional desde movimiento.
-- ============================================================
-- Reglas de esquema:
--   * `plan_mensual.mes` siempre cae el día 1 (CHECK), así un plan es un mes
--     de calendario completo y no una fecha arbitraria.
--   * `partida_plan` NO cascadea desde su plan: el borrado de cuenta elimina
--     primero los hijos (movimientos → partidas → planes), igual que el resto
--     del proyecto (patrón de V10).
--   * `movimiento.partida_id` usa ON DELETE SET NULL: borrar una partida deja
--     el gasto sin partida para que vuelva a imputarse por categoría.
--   * `nombre_normalizado` es la clave de unicidad dentro del plan y el índice
--     que consulta el historial del sugeridor (T10b).
--   * RLS en las dos tablas nuevas (regla de V8/V12).
-- ============================================================

CREATE TABLE IF NOT EXISTS plan_mensual (
    id_plan_mensual    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id         VARCHAR(255)   NOT NULL,
    mes                DATE           NOT NULL,
    ingreso_referencia NUMERIC(19, 2),
    creado_en          TIMESTAMP      NOT NULL,
    actualizado_en     TIMESTAMP      NOT NULL,
    CONSTRAINT pk_plan_mensual   PRIMARY KEY (id_plan_mensual),
    CONSTRAINT fk_plan_usuario   FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT uq_plan_usuario_mes UNIQUE (usuario_id, mes),
    CONSTRAINT chk_plan_mes_dia1 CHECK (EXTRACT(DAY FROM mes) = 1),
    CONSTRAINT chk_plan_ingreso  CHECK (ingreso_referencia IS NULL OR ingreso_referencia >= 0)
);

CREATE TABLE IF NOT EXISTS partida_plan (
    id_partida_plan    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    plan_id            BIGINT         NOT NULL,
    categoria_id       BIGINT         NOT NULL,
    nombre             VARCHAR(80)    NOT NULL,
    nombre_normalizado VARCHAR(80)    NOT NULL,
    monto_planificado  NUMERIC(19, 2) NOT NULL,
    orden              INTEGER        NOT NULL DEFAULT 0,
    actualizado_en     TIMESTAMP      NOT NULL,
    CONSTRAINT pk_partida_plan         PRIMARY KEY (id_partida_plan),
    CONSTRAINT fk_partida_plan         FOREIGN KEY (plan_id)      REFERENCES plan_mensual(id_plan_mensual),
    CONSTRAINT fk_partida_categoria    FOREIGN KEY (categoria_id) REFERENCES categoria(id_categoria),
    CONSTRAINT uq_partida_plan_nombre  UNIQUE (plan_id, nombre_normalizado),
    CONSTRAINT chk_partida_monto       CHECK (monto_planificado >= 0)
);

CREATE INDEX IF NOT EXISTS idx_partida_plan       ON partida_plan (plan_id);
CREATE INDEX IF NOT EXISTS idx_partida_categoria  ON partida_plan (categoria_id);
CREATE INDEX IF NOT EXISTS idx_partida_nombre     ON partida_plan (nombre_normalizado);

-- El movimiento puede imputarse a una partida del mes de su fecha. Es opcional:
-- los movimientos históricos quedan con NULL y se imputan por categoría.
ALTER TABLE movimiento ADD COLUMN IF NOT EXISTS partida_id BIGINT;
ALTER TABLE movimiento DROP CONSTRAINT IF EXISTS fk_mov_partida;
ALTER TABLE movimiento
    ADD CONSTRAINT fk_mov_partida FOREIGN KEY (partida_id)
    REFERENCES partida_plan(id_partida_plan) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_movimiento_partida ON movimiento (partida_id);

ALTER TABLE plan_mensual ENABLE ROW LEVEL SECURITY;
ALTER TABLE partida_plan ENABLE ROW LEVEL SECURITY;
