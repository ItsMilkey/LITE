-- ============================================================
-- V15__preferencia_tipo_usuario.sql  |  PostgreSQL
-- T10d (sesión 1): preferencia de tipo por categoría del usuario.
-- El tipo efectivo = preferencia si existe; si no, el tipo por
-- defecto de la categoría. Solo NECESIDAD o DESEO son
-- reclasificables (no SUELDO, AHORRO ni OTROS).
-- ============================================================
-- Reglas de esquema:
--   * Una fila por (usuario, categoría): UNIQUE uq_pref_usuario_categoria.
--   * FK hacia usuario con ON DELETE CASCADE (patrón V10); la FK hacia
--     categoria no cascadea: el catálogo es global y no se borra (DC1).
--   * RLS activo y constraint/índices en minúscula, sin comillas (G4).
--   * Sin DDL contra migraciones anteriores.
-- ============================================================

CREATE TABLE IF NOT EXISTS preferencia_categoria_usuario (
    id_preferencia   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       VARCHAR(255) NOT NULL,
    categoria_id     BIGINT       NOT NULL,
    tipo_presupuesto VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_preferencia            PRIMARY KEY (id_preferencia),
    CONSTRAINT fk_pref_usuario           FOREIGN KEY (usuario_id)   REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_pref_categoria         FOREIGN KEY (categoria_id) REFERENCES categoria(id_categoria),
    CONSTRAINT uq_pref_usuario_categoria UNIQUE (usuario_id, categoria_id),
    CONSTRAINT chk_pref_tipo             CHECK (tipo_presupuesto IN ('NECESIDAD', 'DESEO'))
);

CREATE INDEX IF NOT EXISTS idx_pref_usuario ON preferencia_categoria_usuario (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pref_categoria ON preferencia_categoria_usuario (categoria_id);

ALTER TABLE preferencia_categoria_usuario ENABLE ROW LEVEL SECURITY;
