-- V6__presupuesto_categoria.sql  |  PostgreSQL (Supabase)
--
-- T5: límite de gasto MENSUAL y recurrente por categoría para cada usuario.
-- El presupuesto 50/30/20 (CONFIGURACION_PRESUPUESTO) reparte por tipo; esta
-- tabla pone un tope concreto por categoría y permite medir la ejecución real
-- (gastado vs. límite) mes a mes.
--
-- Reglas reflejadas en el esquema:
--   * Un límite por (usuario, categoría): UNIQUE.
--   * El límite debe ser estrictamente positivo: CHECK.
--   * Toda tabla nueva expone RLS en Supabase (regla .agents/rules/30-flyway.md).

CREATE TABLE IF NOT EXISTS presupuesto_categoria (
    id_presupuesto_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id               VARCHAR(255)   NOT NULL,
    categoria_id             BIGINT         NOT NULL,
    limite_mensual           NUMERIC(19, 2) NOT NULL,
    CONSTRAINT pk_presupuesto_categoria  PRIMARY KEY (id_presupuesto_categoria),
    CONSTRAINT fk_presup_cat_usuario     FOREIGN KEY (usuario_id)   REFERENCES usuario(id_usuario),
    CONSTRAINT fk_presup_cat_categoria   FOREIGN KEY (categoria_id) REFERENCES categoria(id_categoria),
    CONSTRAINT uq_presup_cat_usuario_cat UNIQUE      (usuario_id, categoria_id),
    CONSTRAINT chk_presup_cat_limite     CHECK       (limite_mensual > 0)
);

ALTER TABLE presupuesto_categoria ENABLE ROW LEVEL SECURITY;
