-- ============================================================
-- V12__notificaciones_push.sql  |  PostgreSQL (Supabase/Render)
-- T9.6: recordatorios de vencimiento de cuotas por push.
-- ============================================================
-- Dos tablas con responsabilidades separadas:
--
--   * DISPOSITIVO_PUSH guarda los tokens de Firebase Cloud Messaging de los
--     teléfonos del usuario. El token es único GLOBAL: un mismo teléfono puede
--     cambiar de cuenta, y en ese caso el servicio lo reasigna en vez de
--     duplicarlo. "activo=false" significa que FCM lo rechazó (app desinstalada,
--     token rotado) y no se vuelve a intentar.
--
--   * RECORDATORIO_ENVIADO es la bitácora de deduplicación: un aviso por
--     (deuda, cuota, tipo). El job puede correr varias veces el mismo día
--     (reintento de Render, trigger manual de cron) sin duplicar la push.
--
-- Ambas FK van con ON DELETE CASCADE: borrar la cuenta (T9.2) o la deuda deja
-- el esquema limpio. RLS habilitado en las dos tablas (regla de V8).
-- ============================================================

CREATE TABLE IF NOT EXISTS dispositivo_push (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       VARCHAR(255) NOT NULL,
    token            VARCHAR(255) NOT NULL,
    plataforma       VARCHAR(10)  NOT NULL,
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro   TIMESTAMP    NOT NULL,
    fecha_ultimo_uso TIMESTAMP    NOT NULL,
    CONSTRAINT pk_dispositivo_push    PRIMARY KEY (id),
    CONSTRAINT fk_disp_push_usuario   FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT uq_disp_push_token     UNIQUE      (token),
    CONSTRAINT chk_disp_push_plataforma CHECK     (plataforma IN ('ANDROID', 'IOS'))
);

-- Listado de dispositivos de un usuario y búsqueda global por token (upsert).
CREATE INDEX IF NOT EXISTS idx_disp_push_usuario ON dispositivo_push (usuario_id);
CREATE INDEX IF NOT EXISTS idx_disp_push_activo  ON dispositivo_push (usuario_id) WHERE activo;

CREATE TABLE IF NOT EXISTS recordatorio_enviado (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id   VARCHAR(255) NOT NULL,
    deuda_id     BIGINT       NOT NULL,
    cuota_numero INT          NOT NULL,
    tipo         VARCHAR(20)  NOT NULL,
    fecha_envio  TIMESTAMP    NOT NULL,
    CONSTRAINT pk_recordatorio_enviado  PRIMARY KEY (id),
    CONSTRAINT fk_rec_env_usuario       FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_rec_env_deuda         FOREIGN KEY (deuda_id)   REFERENCES deuda(id_deuda)     ON DELETE CASCADE,
    CONSTRAINT uq_rec_env_aviso         UNIQUE      (deuda_id, cuota_numero, tipo),
    CONSTRAINT chk_rec_env_tipo         CHECK       (tipo IN ('PROXIMA_VENCER', 'VENCE_HOY', 'VENCIDA'))
);

CREATE INDEX IF NOT EXISTS idx_rec_env_usuario ON recordatorio_enviado (usuario_id);

ALTER TABLE dispositivo_push      ENABLE ROW LEVEL SECURITY;
ALTER TABLE recordatorio_enviado  ENABLE ROW LEVEL SECURITY;
