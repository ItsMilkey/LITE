-- ============================================================
-- V11__token_verificacion.sql  |  PostgreSQL (Supabase/Render)
-- T9.3: tokens de un solo uso para recuperar la contraseña.
-- ============================================================
-- Cada fila es un intento de recuperación. Igual que CONTRASENA_HASH y
-- TOKEN_HASH en AUTH_REFRESH_TOKEN (V9), aquí solo se persiste el hash
-- SHA-256 del token; el valor en claro viaja por correo (o se loguea en
-- dev/test con app.mail.log-only=true).
--
-- Reglas reflejadas en el esquema:
--   * Un token válido 1 hora y de UN solo uso: USADO marca el consumo; la
--     expiración la valida el servicio (PasswordService) con FECHA_EXPIRACION.
--   * Solicitar otra recuperación marca las anteriores como usadas: siempre
--     mandan el último token emitido.
--   * FK hacia USUARIO con ON DELETE CASCADE (T9.2): una cuenta eliminada no
--     deja tokens huérfanos. RLS sobre el esquema público (regla de V8).
-- ============================================================

CREATE TABLE IF NOT EXISTS token_verificacion (
    id_token_verificacion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       VARCHAR(255) NOT NULL,
    tipo             VARCHAR(30)  NOT NULL,
    token_hash       VARCHAR(64)  NOT NULL,
    fecha_expiracion TIMESTAMP    NOT NULL,
    usado            BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_creacion   TIMESTAMP    NOT NULL,
    CONSTRAINT pk_token_verificacion   PRIMARY KEY (id_token_verificacion),
    CONSTRAINT fk_token_ver_usuario    FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT uq_token_ver_token_hash UNIQUE      (token_hash),
    CONSTRAINT chk_token_ver_tipo      CHECK       (tipo IN ('RESET_PASSWORD'))
);

-- Consultas por hash (flujos de restablecimiento) y por usuario (invalidar
-- tokens previos al pedir uno nuevo; inventario en soporte).
CREATE INDEX IF NOT EXISTS idx_token_ver_usuario ON token_verificacion (usuario_id);
CREATE INDEX IF NOT EXISTS idx_token_ver_expiracion ON token_verificacion (fecha_expiracion);

ALTER TABLE token_verificacion ENABLE ROW LEVEL SECURITY;
