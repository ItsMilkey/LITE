-- ============================================================
-- V9__auth_refresh_token.sql  |  PostgreSQL (Supabase/Render)
-- T9.1: sesión móvil con refresh token rotativo y revocable.
-- ============================================================
-- 1) Cada sesión activa es una fila de AUTH_REFRESH_TOKEN. El refresh token
--    que viaja al cliente es un string aleatorio; aquí se guarda únicamente
--    su hash SHA-256 (64 caracteres hexadecimales), igual que CONTRASENA_HASH:
--    nunca el secreto en claro.
-- 2) Rotación: consumir un refresh marca FECHA_USO y FECHA_REVOCACION en su
--    fila y crea una nueva. El reuso de un token revocado revoca todas las
--    sesiones activas del usuario (detección de robo). El logout marca
--    FECHA_REVOCACION. FECHA_EXPIRACION limita la vida útil de cada refresh
--    (90 días desde su emisión).
-- 3) RLS: la tabla vive en el esquema public que Supabase expone por API; el
--    rol del backend la ignora (idempotente, igual que en V8).
-- ============================================================

CREATE TABLE IF NOT EXISTS auth_refresh_token (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       VARCHAR(255) NOT NULL,
    token_hash       VARCHAR(64)  NOT NULL,
    fecha_expiracion TIMESTAMP    NOT NULL,
    fecha_revocacion TIMESTAMP,
    fecha_uso        TIMESTAMP,
    CONSTRAINT pk_auth_refresh_token PRIMARY KEY (id),
    CONSTRAINT fk_auth_rt_usuario    FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario),
    CONSTRAINT uq_auth_rt_token_hash UNIQUE      (token_hash)
);

-- Consultas habituales: revocación masiva por usuario (password reset, robo de token)
-- y búsqueda por hash en los flujos de refresh/logout. PostgreSQL no indexa las FK solo.
CREATE INDEX IF NOT EXISTS idx_auth_rt_usuario ON auth_refresh_token (usuario_id);
CREATE INDEX IF NOT EXISTS idx_auth_rt_expiracion ON auth_refresh_token (fecha_expiracion);
CREATE UNIQUE INDEX IF NOT EXISTS uq_idx_auth_rt_token_hash ON auth_refresh_token (token_hash);

ALTER TABLE auth_refresh_token ENABLE ROW LEVEL SECURITY;
